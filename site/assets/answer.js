// TempDesk answer file kit builder (runs entirely in the browser; nothing is uploaded).
// Produces autounattend.xml + TempDesk/firstboot.json + the TempDesk payload, zipped.
// Must stay compatible with deployer/engine (same file names and firstboot.json schema).
(function () {
  'use strict';

  function xmlEscape(s) {
    return String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
  }

  // Windows unattend password obfuscation: base64(UTF-16LE(password + suffix)). This is NOT encryption.
  function unattendPassword(password, suffix) {
    var s = password + suffix;
    var bytes = new Uint8Array(s.length * 2);
    for (var i = 0; i < s.length; i++) {
      var c = s.charCodeAt(i);
      bytes[i * 2] = c & 0xff;
      bytes[i * 2 + 1] = c >> 8;
    }
    var bin = '';
    for (var j = 0; j < bytes.length; j++) bin += String.fromCharCode(bytes[j]);
    return btoa(bin);
  }

  var COMP = 'processorArchitecture="amd64" publicKeyToken="31bf3856ad364e35" language="neutral" versionScope="nonSxS"';

  function diskXml(firmware) {
    if (firmware === 'bios') {
      return [
        '<DiskConfiguration><Disk wcm:action="add"><DiskID>0</DiskID><WillWipeDisk>true</WillWipeDisk><CreatePartitions>',
        '<CreatePartition wcm:action="add"><Order>1</Order><Type>Primary</Type><Size>500</Size></CreatePartition>',
        '<CreatePartition wcm:action="add"><Order>2</Order><Type>Primary</Type><Extend>true</Extend></CreatePartition>',
        '</CreatePartitions><ModifyPartitions>',
        '<ModifyPartition wcm:action="add"><Order>1</Order><PartitionID>1</PartitionID><Format>NTFS</Format><Label>System</Label><Active>true</Active></ModifyPartition>',
        '<ModifyPartition wcm:action="add"><Order>2</Order><PartitionID>2</PartitionID><Format>NTFS</Format><Label>Windows</Label><Letter>C</Letter></ModifyPartition>',
        '</ModifyPartitions></Disk></DiskConfiguration>'
      ].join('\n        ');
    }
    return [
      '<DiskConfiguration><Disk wcm:action="add"><DiskID>0</DiskID><WillWipeDisk>true</WillWipeDisk><CreatePartitions>',
      '<CreatePartition wcm:action="add"><Order>1</Order><Type>EFI</Type><Size>300</Size></CreatePartition>',
      '<CreatePartition wcm:action="add"><Order>2</Order><Type>MSR</Type><Size>16</Size></CreatePartition>',
      '<CreatePartition wcm:action="add"><Order>3</Order><Type>Primary</Type><Extend>true</Extend></CreatePartition>',
      '</CreatePartitions><ModifyPartitions>',
      '<ModifyPartition wcm:action="add"><Order>1</Order><PartitionID>1</PartitionID><Format>FAT32</Format><Label>System</Label></ModifyPartition>',
      '<ModifyPartition wcm:action="add"><Order>2</Order><PartitionID>2</PartitionID></ModifyPartition>',
      '<ModifyPartition wcm:action="add"><Order>3</Order><PartitionID>3</PartitionID><Format>NTFS</Format><Label>Windows</Label><Letter>C</Letter></ModifyPartition>',
      '</ModifyPartitions></Disk></DiskConfiguration>'
    ].join('\n        ');
  }

  function buildAutounattend(o) {
    var installPartition = o.firmware === 'bios' ? 2 : 3;
    var key = o.productKey
      ? '<ProductKey><Key>' + xmlEscape(o.productKey) + '</Key><WillShowUI>OnError</WillShowUI></ProductKey>'
      : '';
    var firstLogon = "powershell.exe -NoProfile -ExecutionPolicy Bypass -Command \"$f = Get-PSDrive -PSProvider FileSystem | ForEach-Object { Join-Path $_.Root 'TempDesk\\FirstLogon.ps1' } | Where-Object { Test-Path $_ } | Select-Object -First 1; if ($f) { &amp; $f }\"";
    var locale = xmlEscape(o.locale || 'en-US');
    var intl = function (pass) {
      return '<component name="Microsoft-Windows-International-Core' + (pass === 'pe' ? '-WinPE' : '') + '" ' + COMP + '>' +
        (pass === 'pe' ? '<SetupUILanguage><UILanguage>' + locale + '</UILanguage></SetupUILanguage>' : '') +
        '<InputLocale>' + locale + '</InputLocale><SystemLocale>' + locale + '</SystemLocale><UILanguage>' + locale +
        '</UILanguage><UserLocale>' + locale + '</UserLocale></component>';
    };
    return [
      '<?xml version="1.0" encoding="utf-8"?>',
      '<!-- Generated by TempDesk. Contains the Administrator password in Windows unattend encoding (base64, not encryption). Erase the media after installing. -->',
      '<unattend xmlns="urn:schemas-microsoft-com:unattend" xmlns:wcm="http://schemas.microsoft.com/WMIConfig/2002/State">',
      '  <settings pass="windowsPE">',
      '    ' + intl('pe'),
      '    <component name="Microsoft-Windows-Setup" ' + COMP + '>',
      '        ' + diskXml(o.firmware),
      '      <ImageInstall><OSImage><InstallFrom><MetaData wcm:action="add"><Key>/IMAGE/INDEX</Key><Value>' + (parseInt(o.imageIndex, 10) || 1) + '</Value></MetaData></InstallFrom>',
      '        <InstallTo><DiskID>0</DiskID><PartitionID>' + installPartition + '</PartitionID></InstallTo></OSImage></ImageInstall>',
      '      <UserData><AcceptEula>true</AcceptEula>' + key + '</UserData>',
      '    </component>',
      '  </settings>',
      '  <settings pass="specialize">',
      '    <component name="Microsoft-Windows-Shell-Setup" ' + COMP + '>',
      '      <ComputerName>' + xmlEscape(o.computerName) + '</ComputerName>',
      '      <TimeZone>' + xmlEscape(o.timeZone || 'Eastern Standard Time') + '</TimeZone>',
      '    </component>',
      '  </settings>',
      '  <settings pass="oobeSystem">',
      '    ' + intl('oobe'),
      '    <component name="Microsoft-Windows-Shell-Setup" ' + COMP + '>',
      '      <UserAccounts><AdministratorPassword><Value>' + unattendPassword(o.adminPassword, 'AdministratorPassword') + '</Value><PlainText>false</PlainText></AdministratorPassword></UserAccounts>',
      '      <AutoLogon><Password><Value>' + unattendPassword(o.adminPassword, 'Password') + '</Value><PlainText>false</PlainText></Password>',
      '        <Enabled>true</Enabled><LogonCount>1</LogonCount><Username>Administrator</Username></AutoLogon>',
      '      <OOBE><HideEULAPage>true</HideEULAPage><HideLocalAccountScreen>true</HideLocalAccountScreen><HideOnlineAccountScreens>true</HideOnlineAccountScreens><HideWirelessSetupInOOBE>true</HideWirelessSetupInOOBE><ProtectYourPC>3</ProtectYourPC></OOBE>',
      '      <FirstLogonCommands><SynchronousCommand wcm:action="add"><Order>1</Order>',
      '        <CommandLine>' + firstLogon + '</CommandLine>',
      '        <Description>TempDesk unattended setup</Description><RequiresUserInput>false</RequiresUserInput></SynchronousCommand></FirstLogonCommands>',
      '    </component>',
      '  </settings>',
      '</unattend>',
      ''
    ].join('\r\n');
  }

  function buildFirstboot(o) {
    return JSON.stringify({
      computerName: o.computerName,
      ipAddress: o.ipAddress,
      prefixLength: parseInt(o.prefixLength, 10),
      gateway: o.gateway,
      dnsServers: o.dnsServers.split(/[\s,]+/).filter(Boolean),
      domainName: o.domainName,
      netbiosName: o.netbiosName.toUpperCase(),
      functionalLevel: o.functionalLevel || '',
      dsrmPassword: o.dsrmPassword,
      initialAdminUser: 'Administrator',
      agent: { tls: false },
      portals: { mode: o.portalsMode || 'none' }
    }, null, 2) + '\n';
  }

  function validate(o) {
    var errors = {};
    if (!/^[A-Za-z0-9-]{1,15}$/.test(o.computerName) || /^\d+$/.test(o.computerName)) errors.computerName = 'Use 1 to 15 letters, numbers or hyphens (not only numbers).';
    if (!/^[A-Za-z0-9-]+(\.[A-Za-z0-9-]+)+$/.test(o.domainName)) errors.domainName = 'Use a full DNS name such as lab.example.org.';
    if (!/^[A-Za-z0-9-]{1,15}$/.test(o.netbiosName)) errors.netbiosName = 'Use 1 to 15 letters, numbers or hyphens.';
    var ip = /^(25[0-5]|2[0-4]\d|1?\d?\d)(\.(25[0-5]|2[0-4]\d|1?\d?\d)){3}$/;
    if (!ip.test(o.ipAddress)) errors.ipAddress = 'Enter an IPv4 address.';
    if (!ip.test(o.gateway)) errors.gateway = 'Enter an IPv4 address.';
    var p = parseInt(o.prefixLength, 10);
    if (!(p >= 8 && p <= 30)) errors.prefixLength = 'Use a prefix between 8 and 30 (24 is common).';
    var dns = o.dnsServers.split(/[\s,]+/).filter(Boolean);
    if (!dns.length || dns.some(function (d) { return !ip.test(d); })) errors.dnsServers = 'Enter one or more IPv4 addresses, separated by commas.';
    var strong = function (pw) { return pw.length >= 12 && /[a-z]/.test(pw) && /[A-Z]/.test(pw) && /\d/.test(pw) && /[^A-Za-z0-9]/.test(pw); };
    if (!strong(o.adminPassword)) errors.adminPassword = 'At least 12 characters with upper and lower case, a number and a symbol.';
    if (!strong(o.dsrmPassword)) errors.dsrmPassword = 'At least 12 characters with upper and lower case, a number and a symbol.';
    if (o.productKey && !/^([A-Z0-9]{5}-){4}[A-Z0-9]{5}$/i.test(o.productKey)) errors.productKey = 'Format: XXXXX-XXXXX-XXXXX-XXXXX-XXXXX, or leave empty.';
    return errors;
  }

  window.TempDeskAnswer = { buildAutounattend: buildAutounattend, buildFirstboot: buildFirstboot, validate: validate, unattendPassword: unattendPassword };
})();
